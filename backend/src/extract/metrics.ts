/** Width of one character at the given size, in the size's own unit. */
export function advance(ch: string, size: number, family: Family, bold: boolean, italic: boolean): number {
  const code = ch.charCodeAt(0);
  const other = OTHER[ch];
  if (code < 32 || code > 126) return ((other ?? 600) * size) / 1000;
  const name =
    family === 'times'
      ? (`times${bold ? 'Bold' : ''}${italic ? 'Italic' : ''}` as keyof typeof WIDTHS)
      : bold
        ? 'helveticaBold'
        : 'helvetica';
  return (TABLES[name][code - 32] * size) / 1000;
}
